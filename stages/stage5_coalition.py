def verdict(truth, hits):
    wanted, found = set(truth), set(hits)
    return dict(all_identified=found == wanted, any_identified=bool(found & wanted),
                innocent_hit=bool(found - wanted), missed=sorted(wanted-found),
                recall=len(wanted & found)/len(wanted))


@torch.no_grad()
def create_mix(run, dest, pair, first_percent):
    if len(set(pair)) != 2 or not set(pair) <= {"U1","U2","U3"} or not 0 < first_percent < 100:
        raise ValueError("two distinct recipients and a nonzero share for each are required")
    with original(run, pair[0], dest.parent) as a, original(run, pair[1], dest.parent) as b:
        lab = EvaluationModel(a)
        donor = AutoModelForCausalLM.from_pretrained(b, torch_dtype=torch.float32, device_map={"":"cpu"},
                                                      use_safetensors=True, local_files_only=True)
        # Same issuance and architecture: buffers and tokenizer are shared. named_parameters
        # visits the tied embeddings only once. Lerp preserves identical parameters exactly.
        for (name,w), (other,v) in zip(lab.model.named_parameters(), donor.named_parameters(), strict=True):
            if name != other or w.shape != v.shape:
                raise ValueError("model layouts differ")
            w.lerp_(v.to(device=w.device, dtype=w.dtype), (100-first_percent)/100)
        del donor
        with TemporaryDirectory(dir=dest.parent) as work:
            model = Path(work)/"model"
            save_variant(lab, model, "original")
            pack(model, dest)


def evaluate_archive(archive, owner, preds, texts, ev=None, scale=None):
    with TemporaryDirectory(dir=archive.parent) as tmp, ZipFile(archive) as z:
        z.extractall(tmp)  # locally generated by create_mix
        lab = EvaluationModel(Path(tmp))
        quality, _ = lab.utility(texts, preds)
        ratio = quality["perplexity"] / owner["perplexity"]
        result = dict(ppl_ratio=ratio, top1=quality["top1_agreement"],
                      quality_ok=ratio <= 1.10 and quality["top1_agreement"] >= .85)
        if ev is not None:
            _, _, scores = fingerprint(lab, ev, scale)
            result.update(scores)
        return result


def owner_reference(run, scratch):
    texts = ordinary_splits(CORPUS)["eval"]
    with original(run, "owner", scratch) as path:
        owner, preds = EvaluationModel(path).utility(texts)
    return owner, preds, texts


def sweep(args):
    out = args.output
    out.mkdir(parents=True, exist_ok=False)
    ev, scale = batch_evidence(args.stage3_run)
    reference = owner_reference(args.stage3_run, out)
    atomic_json(out/"plan.json", dict(journal=file_hash(args.stage3_run/"journal.jsonl"),
                                     first_weight_percent=args.percent, recipients=["U1","U2","U3"]))
    rows = []
    for pair in itertools.combinations(("U1","U2","U3"), 2):
        for fraction in args.percent:
            with TemporaryDirectory(dir=out) as tmp:
                artifact = Path(tmp)/"mixed.zip"
                create_mix(args.stage3_run, artifact, pair, fraction)
                checksum = file_hash(artifact)
                row = evaluate_archive(artifact, *reference, ev, scale)
                row.update(verdict(pair, row["hits"]), contributors=list(pair), first_percent=fraction,
                           file_sha256=checksum, screened_out=row["screen_matches"] < 12)
                rows.append(row)
                save_rows(out/"coalitions.csv", rows)
                print(pair, fraction, row["hits"], flush=True)
    atomic_json(out/"summary.json", dict(files=len(rows), exact=sum(r["all_identified"] for r in rows),
        at_least_one=sum(r["any_identified"] for r in rows), false_accusations=sum(r["innocent_hit"] for r in rows),
        quality_and_exact=sum(r["quality_ok"] and r["all_identified"] for r in rows), rows=rows))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage3_run", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--percent", type=int, nargs="+", default=[25,50,75])
    args = parser.parse_args()
    if len(set(args.percent)) != len(args.percent) or any(not 0 < p < 100 for p in args.percent):
        parser.error("percent values must be distinct integers from 1 to 99")
    sweep(args)
